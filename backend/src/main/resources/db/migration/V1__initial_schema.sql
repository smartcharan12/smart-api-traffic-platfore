-- V1: initial schema for the Smart API Traffic & Failure Management Platform.
-- Flyway runs this exactly once per database and records it in flyway_schema_history.
-- Never edit an applied migration; add V2__..., V3__... instead.

-- Platform users (dashboard operators / API consumers). Authentication arrives in Phase 4.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email    UNIQUE (email),
    CONSTRAINT ck_users_role     CHECK (role IN ('ADMIN', 'USER'))
);

-- A logical backend service the gateway can route to, e.g. "orders-service" mounted at /orders.
CREATE TABLE services (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(100) NOT NULL,
    base_path               VARCHAR(100) NOT NULL,
    description             VARCHAR(500),
    load_balancing_strategy VARCHAR(30)  NOT NULL DEFAULT 'ROUND_ROBIN',
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_services_name      UNIQUE (name),
    CONSTRAINT uq_services_base_path UNIQUE (base_path),
    CONSTRAINT ck_services_lb_strategy
        CHECK (load_balancing_strategy IN ('ROUND_ROBIN', 'WEIGHTED_ROUND_ROBIN', 'LEAST_CONNECTIONS'))
);

-- One running copy of a service (host:port). A service has many instances (1:N).
CREATE TABLE service_instances (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id        BIGINT       NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    host              VARCHAR(255) NOT NULL,
    port              INT          NOT NULL,
    weight            INT          NOT NULL DEFAULT 1,
    status            VARCHAR(20)  NOT NULL DEFAULT 'UNKNOWN',
    last_heartbeat_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Also serves as the index for "instances of service X" lookups and the FK,
    -- because service_id is its leading column. No separate index on service_id needed.
    CONSTRAINT uq_instance_endpoint UNIQUE (service_id, host, port),
    CONSTRAINT ck_instances_port    CHECK (port BETWEEN 1 AND 65535),
    CONSTRAINT ck_instances_weight  CHECK (weight BETWEEN 1 AND 100),
    CONSTRAINT ck_instances_status  CHECK (status IN ('UNKNOWN', 'HEALTHY', 'DEGRADED', 'DOWN'))
);

-- One row per client request that passed through the gateway (written from Phase 2/3 onward).
-- High write volume, so ids come from a sequence with INCREMENT 50: Hibernate reserves 50 ids
-- per round-trip and can batch inserts. IDENTITY columns force one INSERT round-trip per row.
CREATE SEQUENCE request_logs_seq INCREMENT BY 50;

CREATE TABLE request_logs (
    id             BIGINT        PRIMARY KEY,
    request_id     UUID          NOT NULL,
    user_id        BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    service_id     BIGINT        REFERENCES services (id) ON DELETE SET NULL,
    instance_id    BIGINT        REFERENCES service_instances (id) ON DELETE SET NULL,
    http_method    VARCHAR(10)   NOT NULL,
    path           VARCHAR(2048) NOT NULL,
    client_ip      VARCHAR(45),
    status_code    INT           NOT NULL,
    latency_ms     INT           NOT NULL,
    retry_count    INT           NOT NULL DEFAULT 0,
    failure_reason VARCHAR(500),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Dashboard queries: "latest requests" and "latest requests for service X".
CREATE INDEX idx_request_logs_created_at      ON request_logs (created_at DESC);
CREATE INDEX idx_request_logs_service_created ON request_logs (service_id, created_at DESC);
-- Look up a single request by the id returned to the client in the X-Request-Id header.
CREATE INDEX idx_request_logs_request_id      ON request_logs (request_id);
